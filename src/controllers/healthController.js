/**
 * Controller for application health & system status checks
 */
export const getHealth = async (req, res, next) => {
  // If client specifically requests JSON or is an API client (Accept: application/json)
  const isHtmlExpected = req.accepts(['html', 'json']) === 'html';

  if (isHtmlExpected && !req.query.format) {
    return res.redirect('/dashboard');
  }

  const startTime = Date.now();
  let dbStatus = 'Disconnected';
  let dbLatencyMs = null;

  try {
    const dbStart = Date.now();
    await prisma.$queryRaw`SELECT 1`;
    dbLatencyMs = Date.now() - dbStart;
    dbStatus = 'Connected';
  } catch (err) {
    dbStatus = 'Disconnected';
  }

  const responseTimeMs = Date.now() - startTime;

  return ApiResponse.success(res, {
    statusCode: 200,
    message: 'Bridal & Makeup Business Management API is operational',
    data: {
      status: dbStatus === 'Connected' ? 'UP' : 'DEGRADED',
      timestamp: new Date().toISOString(),
      database: dbStatus,
      databaseLatencyMs: dbLatencyMs,
      responseTimeMs,
      environment: env.NODE_ENV || 'development',
      version: '1.0.0',
    },
  });
};

/**
 * Controller for application readiness check
 * GET /api/ready
 */
export const getReadiness = async (req, res, next) => {
  try {
    const startTime = Date.now();
    await prisma.$queryRaw`SELECT 1`;
    const latencyMs = Date.now() - startTime;

    return ApiResponse.success(res, {
      statusCode: 200,
      message: 'Service is ready to accept traffic',
      data: {
        ready: true,
        database: 'Connected',
        databaseLatencyMs: latencyMs,
        uptimeSeconds: Math.floor(process.uptime()),
        timestamp: new Date().toISOString(),
      },
    });
  } catch (err) {
    return ApiResponse.error(res, {
      statusCode: 503,
      message: 'Service is not ready - Database unavailable',
      data: {
        ready: false,
        database: 'Disconnected',
        timestamp: new Date().toISOString(),
      },
    });
  }
};

